import { promises as fs } from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { SDK_VERSION } from '../shared/versions.js';

const check = process.argv.includes('--check');
const files = ['shared/versions.ts', 'shared/protocol.ts', 'sdk/index.ts'];
const sources = await Promise.all(files.map((file) => fs.readFile(file, 'utf8')));
const combined = sources.map((source, index) => source.replace(/^import .*;\r?\n/gm, '').replace(index < 2 ? /\bexport /g : /export type /g, index < 2 ? '' : 'type ')).join('\n');
const js = `// Generated by npm run sdk:build. Playroom SDK ${SDK_VERSION}; protocol v1.\n` + ts.transpileModule(combined, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
let declaration = '';
const program = ts.createProgram(['sdk/index.ts'], { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, strict: true, skipLibCheck: true, declaration: true, emitDeclarationOnly: true, outDir: '.sdk-types' });
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, { getCanonicalFileName: (name) => name, getCurrentDirectory: () => process.cwd(), getNewLine: () => '\n' }));
program.emit(undefined, (file, data) => { if (file.replaceAll('\\', '/').endsWith('/sdk/index.d.ts')) declaration = data; });
if (!declaration || declaration.includes('import ')) throw new Error('SDK declarations must be self-contained');
const outputs = new Map([
  ['examples/starter/playroom-sdk.js', js], ['examples/starter/playroom-sdk.d.ts', declaration],
  [`artifacts/sdk/${SDK_VERSION}/playroom-sdk.js`, js], [`artifacts/sdk/${SDK_VERSION}/playroom-sdk.d.ts`, declaration],
]);
for (const [file, content] of outputs) {
  if (check && !file.startsWith('artifacts/')) {
    if ((await fs.readFile(file, 'utf8')).replaceAll('\r\n', '\n') !== content) throw new Error(`Generated SDK is stale: ${file}`);
  } else if (!check) { await fs.mkdir(path.dirname(file), { recursive: true }); await fs.writeFile(file, content); }
}
console.info(`SDK ${SDK_VERSION}: ${check ? 'generated files verified' : 'generated JS and declarations'}`);
